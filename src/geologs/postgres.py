"""PostgreSQL/PostGIS connection and schema for the shared Store API."""
from __future__ import annotations

import threading

try:
    import psycopg
    from psycopg.rows import dict_row
except ImportError:  # SQLite installs do not need the optional driver.
    psycopg = None
    dict_row = None


SCHEMA = """
CREATE EXTENSION IF NOT EXISTS postgis;
CREATE TABLE IF NOT EXISTS points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL, external_id TEXT, timestamp TEXT NOT NULL,
    lat DOUBLE PRECISION NOT NULL, lon DOUBLE PRECISION NOT NULL,
    position geography(Point,4326) GENERATED ALWAYS AS
        (ST_SetSRID(ST_MakePoint(lon,lat),4326)::geography) STORED,
    accuracy_m DOUBLE PRECISION, speed_mps DOUBLE PRECISION,
    speed_origin TEXT, mode TEXT NOT NULL,
    UNIQUE(source,external_id), UNIQUE(source,timestamp,lat,lon)
);
CREATE INDEX IF NOT EXISTS points_time ON points(timestamp DESC);
CREATE INDEX IF NOT EXISTS points_source_time ON points(source,timestamp);
CREATE INDEX IF NOT EXISTS points_position ON points USING GIST(position);
CREATE TABLE IF NOT EXISTS point_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_id BIGINT NOT NULL REFERENCES points(id),
    legacy_point_id BIGINT UNIQUE REFERENCES points(id),
    source TEXT NOT NULL, timestamp TEXT NOT NULL,
    lat DOUBLE PRECISION NOT NULL, lon DOUBLE PRECISION NOT NULL,
    accuracy_m DOUBLE PRECISION, speed_mps DOUBLE PRECISION, speed_origin TEXT, received_at TEXT NOT NULL,
    fingerprint TEXT UNIQUE
);
CREATE INDEX IF NOT EXISTS point_observations_time ON point_observations(timestamp DESC);
CREATE INDEX IF NOT EXISTS point_observations_source_time ON point_observations(source,timestamp);
CREATE INDEX IF NOT EXISTS point_observations_source_id ON point_observations(source,id);
CREATE TABLE IF NOT EXISTS places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL, lat DOUBLE PRECISION NOT NULL, lon DOUBLE PRECISION NOT NULL,
    position geography(Point,4326) GENERATED ALWAYS AS
        (ST_SetSRID(ST_MakePoint(lon,lat),4326)::geography) STORED,
    radius_m DOUBLE PRECISION NOT NULL DEFAULT 150, address TEXT,
    category TEXT, provider_place_id TEXT, saved INTEGER DEFAULT 1
);
CREATE UNIQUE INDEX IF NOT EXISTS places_name_ci ON places(lower(name));
CREATE INDEX IF NOT EXISTS places_position ON places USING GIST(position);
CREATE TABLE IF NOT EXISTS reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text TEXT NOT NULL, place_id BIGINT REFERENCES places(id),
    active INTEGER NOT NULL DEFAULT 1, repeat INTEGER NOT NULL DEFAULT 0,
    cooldown_minutes INTEGER NOT NULL DEFAULT 1440,
    created_at TEXT NOT NULL, last_triggered_at TEXT, cancelled_at TEXT,
    destination_name TEXT, destination_address TEXT,
    destination_category TEXT, destination_provider_place_id TEXT, match_name TEXT
);
CREATE INDEX IF NOT EXISTS reminders_active_created ON reminders(active,created_at DESC);
CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reminder_id BIGINT NOT NULL REFERENCES reminders(id),
    point_id BIGINT NOT NULL REFERENCES points(id), triggered_at TEXT NOT NULL,
    webhook_status TEXT DEFAULT 'pending'
);
CREATE INDEX IF NOT EXISTS events_triggered ON events(triggered_at DESC);
CREATE TABLE IF NOT EXISTS source_state (
    source TEXT PRIMARY KEY, point_id BIGINT NOT NULL REFERENCES points(id)
);
CREATE TABLE IF NOT EXISTS observed_stays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL, start_point_id BIGINT NOT NULL UNIQUE REFERENCES points(id),
    end_point_id BIGINT NOT NULL REFERENCES points(id),
    started_at TEXT NOT NULL, ended_at TEXT NOT NULL,
    lat DOUBLE PRECISION NOT NULL, lon DOUBLE PRECISION NOT NULL,
    point_count INTEGER NOT NULL, ongoing INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS observed_stays_time ON observed_stays(started_at);
CREATE TABLE IF NOT EXISTS stay_processing_state (
    source TEXT PRIMARY KEY, last_point_id BIGINT NOT NULL,
    last_timestamp TEXT NOT NULL, candidate TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS observed_stays_v2 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    start_observation_id BIGINT NOT NULL UNIQUE REFERENCES point_observations(id),
    end_observation_id BIGINT NOT NULL REFERENCES point_observations(id),
    started_at TEXT NOT NULL, ended_at TEXT NOT NULL,
    lat DOUBLE PRECISION NOT NULL, lon DOUBLE PRECISION NOT NULL,
    point_count INTEGER NOT NULL, ongoing INTEGER NOT NULL DEFAULT 1,
    kind TEXT NOT NULL DEFAULT 'stationary', activity TEXT,
    distance_m DOUBLE PRECISION, radius_m DOUBLE PRECISION, went_elsewhere INTEGER
);
CREATE INDEX IF NOT EXISTS observed_stays_v2_time ON observed_stays_v2(started_at);
CREATE INDEX IF NOT EXISTS observed_stays_v2_source_time ON observed_stays_v2(source,started_at,ended_at);
CREATE TABLE IF NOT EXISTS stay_observation_state (
    source TEXT PRIMARY KEY, last_observation_id BIGINT NOT NULL,
    last_timestamp TEXT NOT NULL, candidate TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS timeline_fixes (
    observation_id BIGINT PRIMARY KEY REFERENCES point_observations(id) ON DELETE CASCADE,
    source TEXT NOT NULL, role TEXT NOT NULL,
    stay_id BIGINT REFERENCES observed_stays_v2(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS timeline_fixes_source ON timeline_fixes(source);
CREATE TABLE IF NOT EXISTS app_settings (
    key TEXT PRIMARY KEY, value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS analysis_cache (
    cache_key TEXT PRIMARY KEY, watermark TEXT NOT NULL,
    value TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS daily_summaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    summary_date TEXT NOT NULL, timezone TEXT NOT NULL, source TEXT NOT NULL DEFAULT '',
    watermark TEXT NOT NULL, points INTEGER NOT NULL, distance_km DOUBLE PRECISION NOT NULL,
    trip_count INTEGER NOT NULL, place_count INTEGER NOT NULL, reminder_count INTEGER NOT NULL,
    summary TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL, brief TEXT,
    UNIQUE(summary_date,timezone,source)
);
ALTER TABLE daily_summaries ADD COLUMN IF NOT EXISTS brief TEXT;
CREATE INDEX IF NOT EXISTS daily_summaries_date ON daily_summaries(summary_date DESC,timezone);
CREATE TABLE IF NOT EXISTS geocode_cache (
    cache_key TEXT PRIMARY KEY, provider TEXT NOT NULL,
    value TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS reverse_regions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider TEXT NOT NULL, center_lat DOUBLE PRECISION NOT NULL,
    center_lon DOUBLE PRECISION NOT NULL,
    center geography(Point,4326) GENERATED ALWAYS AS
        (ST_SetSRID(ST_MakePoint(center_lon,center_lat),4326)::geography) STORED,
    radius_m DOUBLE PRECISION NOT NULL CHECK (radius_m BETWEEN 0 AND 30),
    value TEXT NOT NULL, created_at TEXT NOT NULL, expires_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS reverse_regions_provider_expiry
    ON reverse_regions(provider,expires_at);
CREATE INDEX IF NOT EXISTS reverse_regions_center ON reverse_regions USING GIST(center);
CREATE TABLE IF NOT EXISTS mode_overrides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL, target TEXT NOT NULL, started_at TEXT NOT NULL, ended_at TEXT NOT NULL,
    mode TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS fuel_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL, effective_date TEXT NOT NULL, price_per_l DOUBLE PRECISION NOT NULL,
    fetched_at TEXT NOT NULL, UNIQUE(source, effective_date)
);
CREATE TABLE IF NOT EXISTS ingest_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL, token_hash TEXT NOT NULL UNIQUE, hint TEXT NOT NULL,
    source TEXT, created_at TEXT NOT NULL, last_used_at TEXT, last_source TEXT
);
CREATE TABLE IF NOT EXISTS stay_edits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL, action TEXT NOT NULL, started_at TEXT NOT NULL, ended_at TEXT NOT NULL,
    lat DOUBLE PRECISION, lon DOUBLE PRECISION, created_at TEXT NOT NULL
);
DROP TABLE IF EXISTS ingest_status;
CREATE TABLE IF NOT EXISTS ingest_devices (
    kind TEXT NOT NULL, device TEXT NOT NULL DEFAULT '', last_attempt_at TEXT NOT NULL,
    last_status INTEGER NOT NULL, last_message TEXT, last_success_at TEXT,
    received INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(kind, device)
);
CREATE TABLE IF NOT EXISTS place_labels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL, lat DOUBLE PRECISION NOT NULL, lon DOUBLE PRECISION NOT NULL,
    radius_m DOUBLE PRECISION NOT NULL, address TEXT, category TEXT, provider_place_id TEXT,
    created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
    source TEXT, started_at TEXT, ended_at TEXT
);
ALTER TABLE place_labels ADD COLUMN IF NOT EXISTS source TEXT;
ALTER TABLE place_labels ADD COLUMN IF NOT EXISTS started_at TEXT;
ALTER TABLE place_labels ADD COLUMN IF NOT EXISTS ended_at TEXT;
CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY);
"""

_schema_lock = threading.Lock()
_initialized_urls = set()


class PostgresConnection:
    def __init__(self, url):
        if psycopg is None:
            raise RuntimeError("PostgreSQL requires psycopg; install with pip install 'geologs[postgres]'")
        self.connection = psycopg.connect(url, row_factory=dict_row)
        with _schema_lock:
            if url not in _initialized_urls:
                for statement in SCHEMA.split(";\n"):
                    if statement.strip():
                        self.connection.execute(statement)
                if not self.connection.execute("SELECT 1 FROM schema_migrations WHERE version=1").fetchone():
                    self.connection.execute("UPDATE points SET mode='running_cycling' WHERE mode='cycling'")
                    self.connection.execute("INSERT INTO schema_migrations(version) VALUES(1)")
                if not self.connection.execute("SELECT 1 FROM schema_migrations WHERE version=2").fetchone():
                    self.connection.execute("""INSERT INTO point_observations
                        (point_id,legacy_point_id,source,timestamp,lat,lon,accuracy_m,speed_mps,received_at)
                        SELECT id,id,source,timestamp,lat,lon,accuracy_m,speed_mps,timestamp FROM points WHERE true
                        ON CONFLICT(legacy_point_id) DO NOTHING""")
                    self.connection.execute("INSERT INTO schema_migrations(version) VALUES(2)")
                if not self.connection.execute("SELECT 1 FROM schema_migrations WHERE version=3").fetchone():
                    self.connection.execute("ALTER TABLE point_observations ADD COLUMN IF NOT EXISTS speed_origin TEXT")
                    self.connection.execute("""UPDATE point_observations o SET speed_mps=p.speed_mps,speed_origin=p.speed_origin
                        FROM points p WHERE p.id=o.point_id AND (o.legacy_point_id IS NOT NULL OR
                        (o.speed_mps IS NULL AND o.timestamp=p.timestamp AND o.lat=p.lat AND o.lon=p.lon
                         AND o.accuracy_m IS NOT DISTINCT FROM p.accuracy_m))""")
                    self.connection.execute("""UPDATE point_observations SET speed_origin='reported'
                        WHERE speed_mps IS NOT NULL AND speed_origin IS NULL""")
                    self.connection.execute("""WITH prior AS (
                        SELECT id,lat,lon,timestamp,
                            LAG(lat) OVER (PARTITION BY source ORDER BY timestamp,id) AS prev_lat,
                            LAG(lon) OVER (PARTITION BY source ORDER BY timestamp,id) AS prev_lon,
                            LAG(timestamp) OVER (PARTITION BY source ORDER BY timestamp,id) AS prev_timestamp
                        FROM point_observations)
                        UPDATE point_observations o SET speed_mps=0,speed_origin='estimated'
                        FROM prior p WHERE o.id=p.id AND o.speed_mps IS NULL
                        AND p.lat=p.prev_lat AND p.lon=p.prev_lon
                        AND p.timestamp::timestamptz-p.prev_timestamp::timestamptz > interval '0 seconds'
                        AND p.timestamp::timestamptz-p.prev_timestamp::timestamptz <= interval '15 minutes'""")
                    self.connection.execute("INSERT INTO schema_migrations(version) VALUES(3)")
                if not self.connection.execute("SELECT 1 FROM schema_migrations WHERE version=4").fetchone():
                    self.connection.execute("""INSERT INTO timeline_fixes(observation_id,source,role,stay_id)
                        SELECT id,source,'movement',NULL FROM point_observations WHERE true
                        ON CONFLICT(observation_id) DO NOTHING""")
                    self.connection.execute("""DELETE FROM timeline_fixes WHERE observation_id IN (
                        SELECT id FROM (SELECT id,ROW_NUMBER() OVER (
                            PARTITION BY source,timestamp ORDER BY COALESCE(accuracy_m,1000000000),id DESC) AS rank
                            FROM point_observations) ranked WHERE rank>1)""")
                    self.connection.execute("""DELETE FROM timeline_fixes t USING point_observations o
                        WHERE t.observation_id=o.id AND EXISTS (
                            SELECT 1 FROM observed_stays_v2 s WHERE s.source=o.source
                            AND o.timestamp>=s.started_at AND o.timestamp<=s.ended_at
                            AND o.id<>s.start_observation_id AND o.id<>s.end_observation_id)""")
                    self.connection.execute("""INSERT INTO timeline_fixes(observation_id,source,role,stay_id)
                        SELECT start_observation_id,source,'arrival',id FROM observed_stays_v2 WHERE true
                        ON CONFLICT(observation_id) DO UPDATE SET role=excluded.role,stay_id=excluded.stay_id""")
                    self.connection.execute("""INSERT INTO timeline_fixes(observation_id,source,role,stay_id)
                        SELECT end_observation_id,source,CASE WHEN ongoing=1 THEN 'latest' ELSE 'departure' END,id
                        FROM observed_stays_v2 WHERE true ON CONFLICT(observation_id) DO UPDATE
                        SET role=excluded.role,stay_id=excluded.stay_id""")
                    self.connection.execute("""WITH candidates AS (
                        SELECT source,candidate::jsonb AS value FROM stay_observation_state
                        WHERE (candidate::jsonb->>'count')::integer>=2
                        AND (candidate::jsonb->>'end')::timestamptz-(candidate::jsonb->>'start')::timestamptz<interval '15 minutes')
                        DELETE FROM timeline_fixes t USING point_observations o,candidates c
                        WHERE t.observation_id=o.id AND o.source=c.source
                        AND o.timestamp>=(c.value->>'start') AND o.timestamp<=(c.value->>'end')
                        AND o.id<>(c.value->>'start_id')::bigint AND o.id<>(c.value->>'end_id')::bigint""")
                    self.connection.execute("""WITH candidates AS (
                        SELECT source,candidate::jsonb AS value FROM stay_observation_state
                        WHERE (candidate::jsonb->>'count')::integer>=2
                        AND (candidate::jsonb->>'end')::timestamptz-(candidate::jsonb->>'start')::timestamptz<interval '15 minutes')
                        INSERT INTO timeline_fixes(observation_id,source,role,stay_id)
                        SELECT (value->>'start_id')::bigint,source,'arrival',NULL FROM candidates WHERE true
                        ON CONFLICT(observation_id) DO UPDATE SET role=excluded.role""")
                    self.connection.execute("""WITH candidates AS (
                        SELECT source,candidate::jsonb AS value FROM stay_observation_state
                        WHERE (candidate::jsonb->>'count')::integer>=2
                        AND (candidate::jsonb->>'end')::timestamptz-(candidate::jsonb->>'start')::timestamptz<interval '15 minutes')
                        INSERT INTO timeline_fixes(observation_id,source,role,stay_id)
                        SELECT (value->>'end_id')::bigint,source,'latest',NULL FROM candidates WHERE true
                        ON CONFLICT(observation_id) DO UPDATE SET role=excluded.role""")
                    self.connection.execute("INSERT INTO schema_migrations(version) VALUES(4)")
                if not self.connection.execute("SELECT 1 FROM schema_migrations WHERE version=6").fetchone():
                    self.connection.execute("UPDATE reminders SET active=0 WHERE repeat=1 AND last_triggered_at IS NOT NULL")
                    self.connection.execute("UPDATE reminders SET repeat=0")
                    self.connection.execute("INSERT INTO schema_migrations(version) VALUES(6)")
                if not self.connection.execute("SELECT 1 FROM schema_migrations WHERE version=7").fetchone():
                    self.connection.execute("ALTER TABLE reminders ADD COLUMN IF NOT EXISTS cancelled_at TEXT")
                    self.connection.execute("""UPDATE reminders SET cancelled_at=created_at
                        WHERE active=0 AND last_triggered_at IS NULL AND cancelled_at IS NULL""")
                    self.connection.execute("INSERT INTO schema_migrations(version) VALUES(7)")
                if not self.connection.execute("SELECT 1 FROM schema_migrations WHERE version=9").fetchone():
                    self.connection.execute("ALTER TABLE places ADD COLUMN IF NOT EXISTS category TEXT")
                    self.connection.execute("ALTER TABLE places ADD COLUMN IF NOT EXISTS provider_place_id TEXT")
                    self.connection.execute("DELETE FROM analysis_cache")
                    self.connection.execute("INSERT INTO schema_migrations(version) VALUES(9)")
                if not self.connection.execute("SELECT 1 FROM schema_migrations WHERE version=10").fetchone():
                    self.connection.execute("ALTER TABLE places ADD COLUMN IF NOT EXISTS saved INTEGER DEFAULT 1")
                    self.connection.execute("ALTER TABLE reminders ADD COLUMN IF NOT EXISTS destination_name TEXT")
                    self.connection.execute("ALTER TABLE reminders ADD COLUMN IF NOT EXISTS destination_address TEXT")
                    self.connection.execute("ALTER TABLE reminders ADD COLUMN IF NOT EXISTS destination_category TEXT")
                    self.connection.execute("ALTER TABLE reminders ADD COLUMN IF NOT EXISTS destination_provider_place_id TEXT")
                    self.connection.execute("""UPDATE reminders r SET destination_name=p.name,
                        destination_address=p.address,destination_category=p.category,
                        destination_provider_place_id=p.provider_place_id FROM places p
                        WHERE p.id=r.place_id AND r.destination_name IS NULL""")
                    self.connection.execute("ALTER TABLE events DROP COLUMN IF EXISTS acknowledged_at")
                    self.connection.execute("INSERT INTO schema_migrations(version) VALUES(10)")
                if not self.connection.execute("SELECT 1 FROM schema_migrations WHERE version=11").fetchone():
                    # Area stays; Store rebuilds existing stays under migration 12.
                    self.connection.execute("""ALTER TABLE observed_stays_v2
                        ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'stationary'""")
                    self.connection.execute("ALTER TABLE observed_stays_v2 ADD COLUMN IF NOT EXISTS activity TEXT")
                    self.connection.execute("ALTER TABLE observed_stays_v2 ADD COLUMN IF NOT EXISTS distance_m DOUBLE PRECISION")
                    self.connection.execute("ALTER TABLE observed_stays_v2 ADD COLUMN IF NOT EXISTS radius_m DOUBLE PRECISION")
                    self.connection.execute("INSERT INTO schema_migrations(version) VALUES(11)")
                if not self.connection.execute("SELECT 1 FROM schema_migrations WHERE version=13").fetchone():
                    # Whether travel before a stay went somewhere else; Store rebuilds under migration 14.
                    self.connection.execute("ALTER TABLE observed_stays_v2 ADD COLUMN IF NOT EXISTS went_elsewhere INTEGER")
                    self.connection.execute("INSERT INTO schema_migrations(version) VALUES(13)")
                if not self.connection.execute("SELECT 1 FROM schema_migrations WHERE version=15").fetchone():
                    # Name-only reminders have no place; they match a place name instead.
                    self.connection.execute("ALTER TABLE reminders ALTER COLUMN place_id DROP NOT NULL")
                    self.connection.execute("ALTER TABLE reminders ADD COLUMN IF NOT EXISTS match_name TEXT")
                    self.connection.execute("INSERT INTO schema_migrations(version) VALUES(15)")
                self.connection.commit()
                _initialized_urls.add(url)

    def execute(self, query, args=()):
        # All dynamic values in Store are parameters. SQL identifiers are fixed.
        return self.connection.execute(query.replace("?", "%s"), args)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


INTEGRITY_ERRORS = (psycopg.IntegrityError,) if psycopg else ()

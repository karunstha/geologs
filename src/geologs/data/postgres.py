# The driver prepares a statement once it has run a few times, and Postgres then plans it once for
# any parameters. That generic plan cannot see that `id > $2` picks out only the newest rows, so
# it walks a source's whole history on every fix: 47 ms instead of 0.02 ms on a three-year
# archive. Planning each run for its own values costs far less than such a plan.
CONNECTION_SETTINGS = {"row_factory": dict_row, "options": "-c plan_cache_mode=force_custom_plan"}


class PostgresConnection:
    """One connection: opened alone, or borrowed from a pool and given back when closed."""

    def __init__(self, connection, release=None):
        self.connection = connection
        self._release = release

    @classmethod
    def connect(cls, url):
        connection = psycopg.connect(app_login_url(url), **CONNECTION_SETTINGS)
        _as_app(connection)
        return cls(connection)

    def execute(self, query, args=()):
        # All dynamic values in Store are parameters. SQL identifiers are fixed.
        return self.connection.execute(query.replace("?", "%s"), args)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        if self._release:
            # Reads leave a transaction open too; end it here rather than have the pool warn.
            if self.connection.info.transaction_status != psycopg.pq.TransactionStatus.IDLE:
                self.connection.rollback()
            self._release(self.connection)
        else:
            self.connection.close()


class PostgresPool:
    """Connections kept open for a server's requests: at most `size` at once, so a burst of requests
    waits its turn (up to `timeout` seconds) rather than exhausting the database's connection limit."""

    def __init__(self, url, size, timeout=10):
        self._pool = ConnectionPool(app_login_url(url), min_size=1, max_size=size, timeout=timeout, open=True,
                                    kwargs=CONNECTION_SETTINGS, check=ConnectionPool.check_connection,
                                    configure=_as_app, name="geologs")

    def connection(self):
        # A connection back from a request is rolled back if it was left mid-transaction.
        return PostgresConnection(self._pool.getconn(), release=self._pool.putconn)

    def close(self):
        self._pool.close()


